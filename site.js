function getSavedLanguage() {
  const saved = localStorage.getItem('siteLanguage');
  if (saved && translations[saved]) {
    return saved;
  }

  const browserLanguage = navigator.language?.slice(0, 2);
  return translations[browserLanguage] ? browserLanguage : 'en';
}

function applyLanguage(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === language));
  });

  localStorage.setItem('siteLanguage', language);
}

function formatRepoDate(value, language) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return '';
  }

  return new Intl.DateTimeFormat(language, {
    month: 'short',
    day: 'numeric',
    year: 'numeric'
  }).format(date);
}

function createRepoCard(repo, language) {
  const card = document.createElement('article');
  card.className = 'repo-card';

  const title = document.createElement('h3');
  const link = document.createElement('a');
  link.href = repo.html_url;
  link.textContent = repo.name.replace(/_/g, ' ');
  title.appendChild(link);

  const description = document.createElement('p');
  description.textContent = repo.description || 'Public repository';

  const meta = document.createElement('div');
  meta.className = 'repo-meta';

  const updated = document.createElement('span');
  updated.textContent = formatRepoDate(repo.updated_at, language);
  meta.appendChild(updated);

  if (repo.language) {
    const languageBadge = document.createElement('span');
    languageBadge.textContent = repo.language;
    meta.appendChild(languageBadge);
  }

  card.append(title, description, meta);
  return card;
}

function renderRepos(repos, language) {
  const grid = document.getElementById('repoGrid');
  if (!grid) {
    return;
  }

  grid.replaceChildren(...repos.slice(0, 6).map(repo => createRepoCard(repo, language)));
}

async function loadGithubRepos(language) {
  try {
    const response = await fetch('https://api.github.com/users/molodchyk/repos?sort=updated&per_page=6', {
      headers: { Accept: 'application/vnd.github+json' }
    });
    if (!response.ok) {
      throw new Error(`GitHub returned ${response.status}`);
    }

    const repos = await response.json();
    renderRepos(Array.isArray(repos) && repos.length > 0 ? repos : fallbackRepos, language);
  } catch {
    renderRepos(fallbackRepos, language);
  }
}

function initializeLanguageSwitcher() {
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => {
      const language = button.dataset.language;
      applyLanguage(language);
      loadGithubRepos(language);
    });
  });
}

function initializeYear() {
  const year = document.getElementById('year');
  if (year) {
    const startYear = 2023;
    const currentYear = new Date().getFullYear();
    year.textContent = currentYear > startYear ? `${startYear} - ${currentYear}` : String(startYear);
  }
}

