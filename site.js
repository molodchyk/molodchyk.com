const themeModes = ['system', 'bright', 'dark'];
const themeStorageKey = 'siteThemeMode';
const supportedLanguages = Object.keys(translations);
const languageStorageKey = 'siteLanguage';
const languageSourceStorageKey = 'siteLanguageSource';

function readStorage(key) {
  try {
    return localStorage.getItem(key);
  } catch {
    return null;
  }
}

function writeStorage(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch {
    // Storage can be unavailable in strict privacy contexts. The current page state still applies.
  }
}

function getSystemTheme() {
  return window.matchMedia?.('(prefers-color-scheme: dark)').matches ? 'dark' : 'bright';
}

function getSavedThemeMode() {
  const saved = readStorage(themeStorageKey);
  return themeModes.includes(saved) ? saved : 'system';
}

function updateThemeColor(resolvedTheme) {
  const meta = document.getElementById('theme-color-meta');
  if (meta) {
    meta.setAttribute('content', resolvedTheme === 'dark' ? '#101419' : '#f6f8fb');
  }
}

function applyThemeMode(mode) {
  const selectedMode = themeModes.includes(mode) ? mode : 'system';
  const resolvedTheme = selectedMode === 'system' ? getSystemTheme() : selectedMode;

  document.documentElement.dataset.themeMode = selectedMode;
  document.documentElement.dataset.resolvedTheme = resolvedTheme;
  document.querySelectorAll('[data-theme-choice]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.themeChoice === selectedMode));
  });

  writeStorage(themeStorageKey, selectedMode);
  updateThemeColor(resolvedTheme);
}

function initializeThemeSwitcher() {
  document.querySelectorAll('[data-theme-choice]').forEach(button => {
    button.addEventListener('click', () => {
      applyThemeMode(button.dataset.themeChoice);
    });
  });

  const systemTheme = window.matchMedia?.('(prefers-color-scheme: dark)');
  if (!systemTheme) {
    return;
  }

  const handleSystemThemeChange = () => {
    if (getSavedThemeMode() === 'system') {
      applyThemeMode('system');
    }
  };

  if (typeof systemTheme.addEventListener === 'function') {
    systemTheme.addEventListener('change', handleSystemThemeChange);
  } else if (typeof systemTheme.addListener === 'function') {
    systemTheme.addListener(handleSystemThemeChange);
  }
}

function normalizeLanguage(value) {
  if (!value || typeof value !== 'string') {
    return null;
  }

  const language = value.toLowerCase();
  if (supportedLanguages.includes(language)) {
    return language;
  }

  const baseLanguage = language.split('-')[0];
  return supportedLanguages.includes(baseLanguage) ? baseLanguage : null;
}

function getSystemLanguage() {
  const languages = Array.isArray(navigator.languages) && navigator.languages.length > 0
    ? navigator.languages
    : [navigator.language];

  for (const language of languages) {
    const supportedLanguage = normalizeLanguage(language);
    if (supportedLanguage) {
      return supportedLanguage;
    }
  }

  return 'en';
}

function getSavedLanguage() {
  const saved = normalizeLanguage(readStorage(languageStorageKey));
  const source = readStorage(languageSourceStorageKey);
  return saved && source === 'manual' ? saved : null;
}

function getInitialLanguage() {
  return getSavedLanguage() || getSystemLanguage();
}

function applyLanguage(language, options = {}) {
  const selectedLanguage = normalizeLanguage(language) || getSystemLanguage();
  const dictionary = translations[selectedLanguage] || translations.en;
  document.documentElement.lang = selectedLanguage;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === selectedLanguage));
  });

  if (options.persist) {
    writeStorage(languageStorageKey, selectedLanguage);
    writeStorage(languageSourceStorageKey, 'manual');
  }
}

function formatRepoDate(value, language) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) {
    return '';
  }

  return new Intl.DateTimeFormat(language, {
    month: 'short',
    day: 'numeric',
    year: 'numeric'
  }).format(date);
}

function createRepoCard(repo, language) {
  const card = document.createElement('article');
  card.className = 'repo-card';

  const title = document.createElement('h3');
  const link = document.createElement('a');
  link.href = repo.html_url;
  link.textContent = repo.name.replace(/_/g, ' ');
  title.appendChild(link);

  const description = document.createElement('p');
  description.textContent = repo.description || 'Public repository';

  const meta = document.createElement('div');
  meta.className = 'repo-meta';

  const updated = document.createElement('span');
  updated.textContent = formatRepoDate(repo.updated_at, language);
  meta.appendChild(updated);

  if (repo.language) {
    const languageBadge = document.createElement('span');
    languageBadge.textContent = repo.language;
    meta.appendChild(languageBadge);
  }

  card.append(title, description, meta);
  return card;
}

function renderRepos(repos, language) {
  const grid = document.getElementById('repoGrid');
  if (!grid) {
    return;
  }

  grid.replaceChildren(...repos.slice(0, 6).map(repo => createRepoCard(repo, language)));
}

async function loadGithubRepos(language) {
  try {
    const response = await fetch('https://api.github.com/users/molodchyk/repos?sort=updated&per_page=6', {
      headers: { Accept: 'application/vnd.github+json' }
    });
    if (!response.ok) {
      throw new Error(`GitHub returned ${response.status}`);
    }

    const repos = await response.json();
    renderRepos(Array.isArray(repos) && repos.length > 0 ? repos : fallbackRepos, language);
  } catch {
    renderRepos(fallbackRepos, language);
  }
}

function initializeLanguageSwitcher() {
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => {
      const language = button.dataset.language;
      applyLanguage(language, { persist: true });
      loadGithubRepos(language);
    });
  });
}

function initializeYear() {
  const year = document.getElementById('year');
  if (year) {
    const startYear = 2023;
    const currentYear = new Date().getFullYear();
    year.textContent = currentYear > startYear ? `${startYear} - ${currentYear}` : String(startYear);
  }
}

